// 事業が合わなくなったタスクの振り分け（HP・システムなど）
export function guessCategory(title, cur) {
  if (cur === '整備') return '整備工場';
  if (cur !== 'HP・システム') return cur;
  if (/アドトラック/.test(title)) return 'アドトラック';
  if (/タクシー/.test(title)) return 'タクシー';
  if (/スパイダー/.test(title)) return 'スパイダー';
  if (/トレーラー/.test(title)) return 'キャンプトレーラー';
  if (/レンタカー/.test(title)) return 'レンタカー';
  return '共通';
}
